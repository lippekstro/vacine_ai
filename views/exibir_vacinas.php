A vacina BCG geralmente deixa uma cicatriz de até 1 cm de diâmetro no braço direito. A reação inclui uma mancha vermelha que evolui para uma pequena ferida e eventualmente cicatriza. Possíveis eventos adversos incluem úlceras grandes, gânglios ou abscessos na pele e disseminação do bacilo da vacina. Os gânglios ocorrem em cerca de 10% dos vacinados. Em caso de qualquer evento adverso, o serviço de vacinação deve notificar as autoridades de saúde e encaminhar o paciente para acompanhamento e tratamento adequados.



Cuidados
Não é necessário nenhum cuidado prévio para a vacinação. A reação no local da aplicação e a formação de cicatriz são esperadas e não requerem produtos, medicamentos ou curativos. A revacinação de crianças sem cicatriz não é mais recomendada pelo Ministério da Saúde desde fevereiro de 2019.



Bebês prematuros com menos de 2Kg de peso corporal não podem tomar a vacina.

